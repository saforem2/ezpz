"""Hang bisect for fsdp_tp: HF+TP>1 vs model/TP isolation.

Why does fsdp_tp hang under `ezpz benchmark` when TP validation passed
3/3 at the same geometry (dp_shard=12, tp=2, ws=24)?

Two variables differ between the passing and hanging configs:
  passing: --model agpt-2b --dataset random    (job 12473890, 86s)
  hanging: --model large   --dataset stanfordnlp/imdb

fsdp_tp.py branches on dataset: `random` uses get_random_dataset_fsdp_tp
with broadcast_within_tp=True; anything else uses _build_hf_dataloader +
TPBroadcastDataLoader. The TP validation only exercised the `random` branch.

This probe isolates which variable matters. Each arm runs in its own
timeout so one hang doesn't eat the allocation, and classification is on
log EVIDENCE (iter count + watchdog markers) not exit code — mpiexec
teardown makes a 10s crash and a 10min deadlock look identical (see
fsdp_tp_bisect.pbs and fsdp_tp_bisect2.pbs for the lineage).

Usage (via ezpz submit):

  ezpz submit -N 2 -q debug --remote aurora -- \
      python3 -m ezpz.experiments.common.fsdp_tp_hang_bisect --trials 5

  ezpz submit --dry-run -N 2 -q debug --remote aurora -- \
      python3 -m ezpz.experiments.common.fsdp_tp_hang_bisect --trials 5

The job script is generated by ezpz submit -- it handles CCL_OP_SYNC=1
(via utils.sh), TORCH_DDP_TIMEOUT, hostfiles, and ezpz launch wrapping.

For the broader hang sweep (XPU seq-parallel + oneCCL 2022.1, EP bmm +
TP=2 + FSDP annotation), see docs/notes/ and SKILL.md.
"""

from __future__ import annotations

import argparse
import os
import re
import shlex
import subprocess
import sys
import time
from pathlib import Path

ARMS: dict[str, dict] = {
    "A": {
        "label": "A-large-random-tp2",
        "desc": "Known-good control: large + random + tp2",
        "argv": ["--model", "large", "--dataset", "random", "--tp", "2"],
        "expect": "TRAINS",
    },
    "B": {
        "label": "B-large-imdb-tp1",
        "desc": "Benchmark dataset, TP off -- isolates HF loader path",
        "argv": ["--model", "large", "--dataset", "stanfordnlp/imdb", "--tp", "1"],
        "expect": "TRAINS",
    },
    "C": {
        "label": "C-large-imdb-tp2",
        "desc": "Failing combo: large + imdb + tp2",
        "argv": ["--model", "large", "--dataset", "stanfordnlp/imdb", "--tp", "2"],
        "expect": "HANG",
    },
    "D": {
        "label": "D-agpt2b-random-tp2",
        "desc": "Originally-passing: agpt-2b + random + tp2 (harness sanity)",
        "argv": ["--model", "agpt-2b", "--dataset", "random", "--tp", "2"],
        "expect": "TRAINS",
    },
}

ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")
ITER_RE = re.compile(r"iter=\d+")
WATCHDOG_RE = re.compile(r"Watchdog|PROGRESS TIMEOUT|Abort\(|NCCL.*timeout|CCL.*timeout", re.I)


def strip_ansi(text: str) -> str:
    return ANSI_RE.sub("", text)


def classify_log(stripped: str, return_code: int) -> tuple[str, str]:
    if not stripped.strip():
        return "INDETERMINATE", "log EMPTY -- launch likely never started"
    iters = len(ITER_RE.findall(stripped))
    has_watchdog = bool(WATCHDOG_RE.search(stripped))
    if re.search(r"iter=(?:4|5)\b", stripped):
        return "TRAINS", f"{iters} iters, rc={return_code}"
    if has_watchdog:
        return "HANG-COLLECTIVE", f"watchdog/timeout, {iters} iters, rc={return_code}"
    if return_code == 124:
        return "HANG-WALLCLOCK", f"timeout exit 124, {iters} iters"
    if return_code == 0:
        if iters > 0:
            return "TRAINS", f"{iters} iters, rc=0"
        return "INDETERMINATE", "rc=0 but no iter marker -- check log tail"
    tail_lines = [line for line in stripped.splitlines() if line.strip()][-2:]
    tail = " | ".join(line.strip() for line in tail_lines)[:200]
    return "OTHER", f"rc={return_code}, {iters} iters :: {tail}"


def run_arm(
    arm_key: str,
    arm_cfg: dict,
    trial: int,
    outdir: Path,
    timeout_s: int,
    train_iters: int,
    extra_argv: list[str],
) -> dict:
    label = arm_cfg["label"]
    argv = list(arm_cfg["argv"]) + ["--train-iters", str(train_iters)] + list(extra_argv)
    log_path = outdir / f"{label}.trial{trial}.log"
    cmd = [sys.executable, "-m", "ezpz.examples.fsdp_tp"] + argv
    env = dict(os.environ)
    env.setdefault("PYTHONUNBUFFERED", "1")
    env.setdefault("HF_HUB_OFFLINE", "1")
    env.setdefault("HF_DATASETS_OFFLINE", "1")
    env.setdefault("TRANSFORMERS_OFFLINE", "1")
    env.setdefault("WANDB_MODE", "disabled")
    env.setdefault("TORCH_DDP_TIMEOUT", "240")
    if "CCL_OP_SYNC" not in env:
        env["CCL_OP_SYNC"] = "1"
    outdir.mkdir(parents=True, exist_ok=True)
    start = time.monotonic()
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        env=env,
        text=True,
        bufsize=1,
    )
    try:
        out, _ = proc.communicate(timeout=timeout_s)
        return_code = proc.returncode
    except subprocess.TimeoutExpired:
        proc.kill()
        try:
            out, _ = proc.communicate(timeout=10)
        except Exception:
            out = ""
        return_code = 124
        out = (out or "") + f"\n[fsdp_tp_hang_bisect] WATCHDOG: killed after {timeout_s}s"
    elapsed = time.monotonic() - start
    tmp = log_path.with_suffix(log_path.suffix + ".tmp")
    tmp.write_text(out or "", encoding="utf-8", errors="replace")
    tmp.replace(log_path)
    stripped = strip_ansi(out or "")
    verdict, detail = classify_log(stripped, return_code)
    iters = len(ITER_RE.findall(stripped))
    msg = f"    -> {verdict}  {detail}  ({elapsed:.1f}s)"
    print(msg, flush=True)
    return {
        "arm": arm_key,
        "label": label,
        "trial": trial,
        "rc": return_code,
        "elapsed_s": round(elapsed, 2),
        "iters": iters,
        "verdict": verdict,
        "detail": detail,
        "log": str(log_path),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--arm", type=str, default=None, help="Single arm key (A/B/C/D).")
    parser.add_argument(
        "--suite",
        type=str,
        default=None,
        choices=["smoke", "bisect", "full"],
        help="Named suite to run (default: bisect).",
    )
    parser.add_argument("--list-arms", action="store_true", help="List arms and exit.")
    parser.add_argument("--trials", type=int, default=3, help="Trials per arm (default: 3).")
    parser.add_argument("--timeout", type=int, default=600, help="Per-trial timeout seconds (default: 600).")
    parser.add_argument("--train-iters", type=int, default=5, help="--train-iters for fsdp_tp (default: 5).")
    parser.add_argument("--outdir", type=str, default=None, help="Output dir for logs/report.")
    parser.add_argument("--extra-args", type=str, default="", help="Extra args forwarded to fsdp_tp.")
    args = parser.parse_args()
    if args.list_arms:
        for key, cfg in ARMS.items():
            print(f"  {key}: {cfg['label']:28s} expect={cfg['expect']:10s}  {cfg['desc']}")
            print(f"      argv: {shlex.join(cfg['argv'])}")
        print("\nSuites: smoke=[D,A]  bisect=[A,B,C,D]  full=[A,B,C,D]")
        return 0
    suites: dict[str, list[str]] = {
        "smoke": ["D", "A"],
        "bisect": ["A", "B", "C", "D"],
        "full": ["A", "B", "C", "D"],
    }
    if args.arm and args.suite:
        print("error: specify --arm or --suite, not both", file=sys.stderr)
        return 2
    if args.arm:
        if args.arm not in ARMS:
            print(f"error: unknown arm {args.arm!r}", file=sys.stderr)
            return 2
        suite = [args.arm]
    elif args.suite:
        suite = suites[args.suite]
    else:
        suite = suites["bisect"]
    timestamp = time.strftime("%Y%m%d-%H%M%S")
    outdir = Path(args.outdir) if args.outdir else Path.cwd() / "out" / f"hang-bisect-{timestamp}"
    outdir.mkdir(parents=True, exist_ok=True)
    manifest = {
        "ts": timestamp,
        "suite": suite,
        "arms": {key: ARMS[key] for key in suite},
        "trials": args.trials,
        "timeout_s": args.timeout,
        "train_iters": args.train_iters,
        "outdir": str(outdir),
        "extra_args": args.extra_args,
    }
    import json as _json

    (outdir / "manifest.json").write_text(_json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"[fsdp_tp_hang_bisect] outdir={outdir} suite={suite} trials={args.trials} timeout={args.timeout}s")
    extra = shlex.split(args.extra_args) if args.extra_args else []
    results: list[dict] = []
    for arm_key in suite:
        cfg = ARMS[arm_key]
        print(f"\n===== ARM {arm_key}: {cfg['label']}  expect={cfg['expect']} =====")
        for trial in range(1, args.trials + 1):
            print(f"  trial {trial}/{args.trials} ...", flush=True)
            result = run_arm(arm_key, cfg, trial, outdir, args.timeout, args.train_iters, extra)
            results.append(result)
    report = {"manifest": manifest, "results": results}
    report_path = outdir / "report.json"
    report_path.write_text(_json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(f"\n[fsdp_tp_hang_bisect] report: {report_path}")
    print("\n===== SUMMARY =====")
    from collections import Counter as _Counter

    for key in suite:
        arm_results = [r for r in results if r["arm"] == key]
        cfg = ARMS[key]
        counts = _Counter(r["verdict"] for r in arm_results)
        parts = ", ".join(f"{verdict}={num}" for verdict, num in sorted(counts.items()))
        if cfg["expect"] == "HANG":
            ok = all(r["verdict"].startswith("HANG") for r in arm_results)
        else:
            ok = all(r["verdict"] == cfg["expect"] for r in arm_results)
        status = "PASS" if ok else "MIXED"
        print(f"  {key} {cfg['label']:28s} expect={cfg['expect']:10s}  {parts}  => {status}")
    hangs = sum(1 for r in results if r["verdict"].startswith("HANG"))
    print(f"\n  HANG detected: {hangs}/{len(results)} trials")
    print(f"  logs: {outdir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
